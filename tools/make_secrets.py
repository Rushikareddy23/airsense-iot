"""Write firmware/include/secrets.h and certs/ for one device from Terraform outputs.

  cd infra/terraform && terraform output -json > ../../outputs.json && cd ../..
  python tools/make_secrets.py --device airsense-01 --wifi-ssid "MyWiFi" --wifi-password "..." outputs.json
  rm outputs.json        # it contains private keys
"""
import argparse
import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ROOT_CA_URL = "https://www.amazontrust.com/repository/AmazonRootCA1.pem"


def c_string(name: str, pem: str) -> str:
    return f'static const char {name}[] = R"PEM(\n{pem.strip()}\n)PEM";\n'


def c_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def build_header(device, endpoint, ssid, password, root_ca, cert, key) -> str:
    return (
        "// Generated by tools/make_secrets.py. Contains a private key: never commit.\n#pragma once\n\n"
        f'#define WIFI_SSID "{c_escape(ssid)}"\n#define WIFI_PASSWORD "{c_escape(password)}"\n'
        f'#define DEVICE_ID "{c_escape(device)}"\n#define AWS_IOT_ENDPOINT "{c_escape(endpoint)}"\n\n'
        + c_string("AWS_ROOT_CA", root_ca) + "\n" + c_string("DEVICE_CERT", cert) + "\n"
        + c_string("DEVICE_PRIVATE_KEY", key))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outputs_json")
    ap.add_argument("--device", default="airsense-01")
    ap.add_argument("--wifi-ssid", required=True)
    ap.add_argument("--wifi-password", required=True)
    a = ap.parse_args()
    out = json.loads(Path(a.outputs_json).read_text())
    certs = out["device_certificates"]["value"]
    if a.device not in certs:
        raise SystemExit(f"device {a.device!r} not in Terraform outputs: {list(certs)}")
    cert, key = certs[a.device]["certificate_pem"], certs[a.device]["private_key"]
    root_ca = urllib.request.urlopen(ROOT_CA_URL, timeout=20).read().decode()
    header = build_header(a.device, out["iot_endpoint"]["value"], a.wifi_ssid, a.wifi_password, root_ca, cert, key)
    (ROOT / "firmware" / "include" / "secrets.h").write_text(header)
    certs_dir = ROOT / "certs"
    certs_dir.mkdir(exist_ok=True)
    (certs_dir / f"{a.device}.pem.crt").write_text(cert)
    (certs_dir / f"{a.device}.private.pem.key").write_text(key)
    (certs_dir / "AmazonRootCA1.pem").write_text(root_ca)
    print("Wrote firmware/include/secrets.h and certs/ (both git-ignored).")


if __name__ == "__main__":
    main()
